// Writes the nginx security-header snippet for the generated site.
// Nuxt inlines a few scripts (runtime config, import map) whose content changes per build,
// so their CSP hashes are computed from the output instead of allowing 'unsafe-inline'.
//
//   node scripts/security-headers.mjs <public dir> <output .conf>
import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const [publicDir = '.output/public', outFile = 'security-headers.conf'] = process.argv.slice(2)

async function* htmlFiles(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) yield* htmlFiles(path)
    else if (entry.name.endsWith('.html')) yield path
  }
}

const hashes = new Set()
for await (const file of htmlFiles(publicDir)) {
  const html = await readFile(file, 'utf8')
  for (const [, attrs, body] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)) {
    if (/\bsrc=/.test(attrs) || /type="application\/(?:ld\+)?json"/.test(attrs) || !body) continue
    hashes.add(`'sha256-${createHash('sha256').update(body).digest('base64')}'`)
  }
}

// Misskey instances are arbitrary hosts, so API, streaming and media stay open to any HTTPS origin.
const csp = [
  `default-src 'self'`,
  `script-src 'self' ${[...hashes].join(' ')}`.trim(),
  `style-src 'self' 'unsafe-inline'`,
  `img-src 'self' https: data: blob:`,
  `media-src 'self' https: blob:`,
  `connect-src 'self' https: wss:`,
  `font-src 'self' data:`,
  // Click-to-play link players; keep in sync with PLAYER_HOSTS in app/utils/embed.ts
  `frame-src https://www.youtube-nocookie.com https://www.youtube.com https://w.soundcloud.com https://player.vimeo.com https://open.spotify.com https://embed.nicovideo.jp https://bandcamp.com`,
  `worker-src 'self'`,
  `manifest-src 'self'`,
  `object-src 'none'`,
  `base-uri 'none'`,
  `form-action 'none'`,
  `frame-ancestors 'none'`,
].join('; ')

await writeFile(outFile, `# Generated by scripts/security-headers.mjs — do not edit
add_header Content-Security-Policy "${csp}" always;
add_header X-Content-Type-Options "nosniff" always;
add_header X-Frame-Options "DENY" always;
add_header Referrer-Policy "strict-origin-when-cross-origin" always;
add_header Permissions-Policy "camera=(), microphone=(), geolocation=()" always;
`)
console.log(`${outFile}: ${hashes.size} inline script hash(es)`)
